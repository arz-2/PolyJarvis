#!/usr/bin/env python3
"""Leg and point registry for the round-2 bulk-modulus diagnostics on sPVC_3.

Mirrors ~/PolyJarvis/data/murnaghan_diagnostics (round-1 PVC3, old equilibration protocol) on a
current-protocol cell: sPVC_3's accepted 300 K cooling output (npt_final_out.data, copied to
data/bm_diagnostics_r2/input/). Every simulated point is generated by the production
run_bulk_modulus_series path (deck verified byte-identical to sPVC_3's production deck at
-1000 atm apart from the swept knob), one pressure per chain, exactly as do_mechanical runs it.

A point is keyed by (pressure_atm, barostat_damp_fs, npt_steps). Points that match sPVC_3's own
production series reuse its logs; everything else is simulated once and shared by every leg that
needs it. `nptsteps_250k` is analysis-only: the first 250,000 steps of each baseline log are the
same trajectory a 250k-step point would produce from the same cell and velocities.
"""
from __future__ import annotations

from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
RUN_AREA = REPO / "data" / "bm_diagnostics_r2"
INPUT_CELL = RUN_AREA / "input" / "sPVC_3_npt_final_out.data"
INPUT_CELL_SHA256 = "25c0b6f368955dfddbd89b1f51dcbded24969a6ae20e7fc4bedaa0565831e862"
PROD = REPO / "data" / "sPVC_3" / "attempts" / "mechanical" / "attempt-0001" / "work" / "bm_series"

# Production settings of sPVC_3's mechanical stage (executor_state parameters + deck).
TEMP_K = 300.0
DT_FS = 1.0
THERMO_FREQ = 100
T_DAMP_FS = 100.0
BASE_DAMP_FS = 1000.0
BASE_STEPS = 500_000
VELOCITY_SEED = 585758416      # sPVC_3's velocity_seed; decks read velocities from the data file
MPI = 1
ENGINE = "kokkos"
BASE_LADDER = [-1000, 0, 1500, 3000, 5000]


def key(p: float, damp: float = BASE_DAMP_FS, steps: int = BASE_STEPS) -> str:
    return f"P{int(p)}_damp{int(damp)}_steps{int(steps)}"


def production_log(p: int) -> Path:
    return PROD / f"p_{p:g}" / "attempt_1" / f"bm_P{int(p)}" / f"bm_P{int(p)}.log"


def simulated_log(k: str, p: float) -> Path:
    return RUN_AREA / "points" / k / f"bm_P{int(p)}" / f"bm_P{int(p)}.log"


# leg -> list of (pressure, damp, steps); "analysis" marks legs that need no new simulation.
LEGS: dict[str, dict] = {
    "baseline":          {"axis": "sPVC_3 production series (reused)", "points": [(p, BASE_DAMP_FS, BASE_STEPS) for p in BASE_LADDER]},
    "pdamp_250":         {"axis": "barostat damping 250 fs", "points": [(p, 250.0, BASE_STEPS) for p in BASE_LADDER]},
    "pdamp_4000":        {"axis": "barostat damping 4000 fs", "points": [(p, 4000.0, BASE_STEPS) for p in BASE_LADDER]},
    "nptsteps_250k":     {"axis": "production 250k steps (first half of baseline logs)", "analysis": "truncate", "points": [(p, BASE_DAMP_FS, BASE_STEPS) for p in BASE_LADDER]},
    "nptsteps_1M":       {"axis": "production 1M steps", "points": [(p, BASE_DAMP_FS, 1_000_000) for p in BASE_LADDER]},
    "span_check":        {"axis": "ladder span +/-1000 atm", "points": [(p, BASE_DAMP_FS, BASE_STEPS) for p in (-1000, -500, 0, 500, 1000)]},
    "points_7":          {"axis": "7-point ladder", "points": [(p, BASE_DAMP_FS, BASE_STEPS) for p in (-1000, 0, 750, 1500, 3000, 4000, 5000)]},
    "wide_compression":  {"axis": "15000 atm ceiling", "points": [(p, BASE_DAMP_FS, BASE_STEPS) for p in (-1000, 0, 3000, 7000, 15000)]},
    "no_tension":        {"axis": "no tension point (round-1 ladder 1-5000 atm)", "points": [(p, BASE_DAMP_FS, BASE_STEPS) for p in (1, 1250, 2500, 3750, 5000)]},
    "no_tension_prod":   {"axis": "baseline without -1000 atm (production fit window)", "analysis": "subset", "points": [(p, BASE_DAMP_FS, BASE_STEPS) for p in (0, 1500, 3000, 5000)]},
    "tension_series":    {"axis": "tension resolution -1000..0 atm", "points": [(p, BASE_DAMP_FS, BASE_STEPS) for p in (-1000, -500, -250, 0)]},
}
# The 1M-step repeat at -1000 atm requested for the tension question is the nptsteps_1M point
# P-1000_damp1000_steps1000000; it is simulated once and used by both analyses.

# Simulation priority: tension question first, then barostat, length, ladder shape.
PRIORITY = ["tension_series", "span_check", "pdamp_250", "pdamp_4000", "nptsteps_1M",
            "points_7", "wide_compression", "no_tension"]


def point_source(p: float, damp: float, steps: int) -> tuple[str, Path]:
    """('production', log) when sPVC_3's own series has this point, else ('simulate', log)."""
    if damp == BASE_DAMP_FS and steps == BASE_STEPS and int(p) in BASE_LADDER:
        return "production", production_log(int(p))
    k = key(p, damp, steps)
    return "simulate", simulated_log(k, p)


def points_to_simulate() -> list[tuple[float, float, int]]:
    seen, out = set(), []
    for leg in PRIORITY:
        for p, d, s in LEGS[leg]["points"]:
            src, _ = point_source(p, d, s)
            k = key(p, d, s)
            if src == "simulate" and k not in seen:
                seen.add(k)
                out.append((p, d, s))
    return out


def est_gpu_hours(points) -> float:
    per_500k_h = 1491.25 / 3600.0   # sPVC_3 production loop time at -1000 atm, 500k steps, KOKKOS mpi=1
    return sum(per_500k_h * s / BASE_STEPS for _, _, s in points)


if __name__ == "__main__":
    pts = points_to_simulate()
    for leg, spec in LEGS.items():
        new = [key(*pt) for pt in spec["points"] if point_source(*pt)[0] == "simulate"]
        print(f"{leg:18} {spec['axis']:55} P={[int(p) for p, _, _ in spec['points']]} new={len(new)}")
    print(f"distinct new points: {len(pts)}  est GPU-h: {est_gpu_hours(pts):.1f}")
